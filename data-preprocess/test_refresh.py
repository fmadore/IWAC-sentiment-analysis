"""The orchestrated refresh, end to end on fake sources and the real validator.

The fake upstream is a handful of rows carrying both generations' columns, as
the real parquet does. Each test publishes into a temporary ``static/data``
and checks what the dashboard would then see.
"""

from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path

import pandas as pd
import pytest
from iwac_preprocess import BASE_FILENAME, CONTRACT_V1, CONTRACT_V2
from iwac_preprocess.publication import JOURNAL
from iwac_preprocess.refresh import RefreshSources, plan_generations, refresh_all
from test_generation import fake_record
from validate_generated_data import ContractError, validate_all

LOGGER = logging.getLogger("test_refresh")
REVISION = "0123456789abcdef0123456789abcdef01234567"


def upstream_row(article_id: int) -> dict:
    row = {**fake_record(article_id, CONTRACT_V1), **fake_record(article_id, CONTRACT_V2)}
    row["spatial"] = "Lomé" if article_id % 2 else "Bamako|Lomé"
    return row


def index_frame() -> pd.DataFrame:
    return pd.DataFrame(
        [
            {"o:id": 10, "Type": "Lieux", "Titre": "Lomé", "Coordonnées": "6.13, 1.22"},
            {"o:id": 11, "Type": "Lieux", "Titre": "Bamako", "Coordonnées": "12.63, -8.0"},
        ]
    )


class FakeUpstream:
    def __init__(self, ids):
        self.ids = list(ids)
        self.loads: list[str] = []

    def sources(self) -> RefreshSources:
        def load_records(contract):
            self.loads.append(contract.analysis_version)
            return [upstream_row(article_id) for article_id in self.ids]

        return RefreshSources(
            load_records=load_records,
            load_index=index_frame,
            source_revision=lambda: REVISION,
            repository="example/corpus",
        )


def empty_v1_arbiters(target: Path) -> None:
    """The v1 pairwise files are frozen and never regenerated by a refresh."""
    for pair in CONTRACT_V1.model_pairs:
        (target / f"iwac_arbiter_evaluations_{pair}.json").write_text(
            json.dumps(
                {
                    "metadata": {
                        "pair": pair,
                        "contract_schema_version": CONTRACT_V1.schema_version,
                        "analysis_version": CONTRACT_V1.analysis_version,
                        "successful_evaluations": 0,
                    },
                    "evaluations": [],
                }
            ),
            encoding="utf-8",
        )


@pytest.fixture
def published(tmp_path):
    """A complete published set for articles 1-3, built by a first full refresh."""
    target, staging = tmp_path / "data", tmp_path / "staging"
    target.mkdir()
    empty_v1_arbiters(target)
    refresh_all(
        target,
        staging,
        validate=validate_all,
        include_v1=True,
        sources=FakeUpstream([1, 2, 3]).sources(),
        logger=LOGGER,
    )
    return target, staging


def digests(directory: Path) -> dict[str, str]:
    return {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(directory.iterdir())
        if path.is_file()
    }


def base_ids(target: Path) -> list[int]:
    return [row["o:id"] for row in json.loads((target / BASE_FILENAME).read_text("utf-8"))]


def test_a_first_full_refresh_publishes_a_set_that_validates(published):
    target, _ = published
    validate_all(target)
    assert base_ids(target) == [1, 2, 3]
    manifest = json.loads((target / "iwac_data_manifest_v2.json").read_text("utf-8"))
    assert manifest["source"] == {"repository": "example/corpus", "revision": REVISION}
    for name in ("iwac_places.json", "iwac_extreme_analysis_luna.json"):
        source = json.loads((target / name).read_text("utf-8"))["source"]
        assert source["revision"] == REVISION
    assert not (target / JOURNAL).exists()


def test_the_default_refresh_leaves_v1_and_the_base_untouched(published):
    target, staging = published
    before = digests(target)
    upstream = FakeUpstream([1, 2, 3, 4])  # article 4 ingested since the base
    refresh_all(target, staging, validate=validate_all, sources=upstream.sources())
    after = digests(target)
    assert upstream.loads == ["v2"]
    frozen = [name for name in before if "v2" not in name and not _is_v2_model_file(name)]
    for name in frozen:
        if name in {"iwac_places.json"}:
            continue  # regenerated: generation-independent, re-stamped
        assert after[name] == before[name], name
    assert base_ids(target) == [1, 2, 3]  # the new article stays out
    validate_all(target)


def _is_v2_model_file(name: str) -> bool:
    return any(f"_{model_id}" in name for model_id in CONTRACT_V2.model_names)


def test_an_upstream_deletion_fails_a_v2_refresh_and_publishes_nothing(published):
    target, staging = published
    before = digests(target)
    with pytest.raises(SystemExit, match="gone from the Hugging Face corpus"):
        refresh_all(target, staging, validate=validate_all, sources=FakeUpstream([1, 3]).sources())
    assert digests(target) == before


def test_including_v1_reconciles_a_deletion_across_every_file(published):
    target, staging = published
    refresh_all(
        target,
        staging,
        validate=validate_all,
        include_v1=True,
        sources=FakeUpstream([1, 3]).sources(),
    )
    assert base_ids(target) == [1, 3]
    validate_all(target)  # coverage, manifests, extremes denominators, places


def test_new_articles_are_admitted_only_with_v1_and_the_flag(published):
    target, staging = published
    with pytest.raises(SystemExit, match="--include-v1"):
        refresh_all(
            target,
            staging,
            validate=validate_all,
            admit_new_articles=True,
            sources=FakeUpstream([1, 2, 3, 4]).sources(),
        )
    refresh_all(
        target,
        staging,
        validate=validate_all,
        include_v1=True,
        admit_new_articles=True,
        sources=FakeUpstream([1, 2, 3, 4]).sources(),
    )
    assert base_ids(target) == [1, 2, 3, 4]
    validate_all(target)


def test_a_stage_the_validator_rejects_publishes_nothing(published):
    target, staging = published
    before = digests(target)

    def reject(stage):
        raise ContractError("invalid stage")

    with pytest.raises(ContractError):
        refresh_all(target, staging, validate=reject, sources=FakeUpstream([1, 2, 3]).sources())
    assert digests(target) == before
    assert not (target / JOURNAL).exists()


def test_a_dry_run_validates_the_whole_stage_but_publishes_nothing(published):
    target, staging = published
    before = digests(target)
    seen = []

    def record(stage):
        seen.append(sorted(path.name for path in stage.iterdir()))
        validate_all(stage)

    names = refresh_all(
        target,
        staging,
        validate=record,
        publish=False,
        sources=FakeUpstream([1, 2, 3]).sources(),
    )
    assert digests(target) == before
    # The validator saw the complete set, not only the regenerated files.
    assert set(seen[0]) >= set(before)
    assert names[-1] == "iwac_data_manifest_v2.json"


def test_manifests_are_promoted_last():
    from iwac_preprocess.refresh import _manifests_last

    assert _manifests_last(
        ["iwac_data_manifest.json", "a.json", "iwac_data_manifest_v2.json", "a.json", "b.json"]
    ) == ["a.json", "b.json", "iwac_data_manifest.json", "iwac_data_manifest_v2.json"]


